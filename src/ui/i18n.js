export function getLang() {
  try {
    const l = localStorage.getItem('roboarena3d.lang');
    if (l === 'ru' || l === 'en') return l;
  } catch { /* пусто */ }
  return (navigator.language || 'ru').toLowerCase().startsWith('en') ? 'en' : 'ru';
}

export function t(key, lang) {
  const l = lang || getLang();
  return (DICT[l] && DICT[l][key]) || DICT.ru[key] || key;
}

export function applyI18n(lang) {
  const l = lang || getLang();
  document.documentElement.lang = l;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const v = t(el.dataset.i18n, l);
    if (v !== undefined) el.textContent = v;
  }
  for (const el of document.querySelectorAll('[data-i18n-tt]')) {
    const v = t(el.dataset.i18nTt, l);
    if (v !== undefined) el.title = v;
  }
}

export function setLang(lang) {
  try { localStorage.setItem('roboarena3d.lang', lang); } catch { /* пусто */ }
  applyI18n(lang);
}
